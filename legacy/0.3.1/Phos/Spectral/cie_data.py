# XYZ(D65) → 线性 sRGB
XYZ_TO_SRGB = np.linalg.inv(SRGB_TO_XYZ)

# D65 白点（sRGB 白场 R=G=B=1 的 XYZ，Y 归一化为 1）
WHITE_XYZ = SRGB_TO_XYZ @ np.ones(3)


def verify_constants():
    """自检：白点 XYZ 应与 sRGB 标准白点接近；RGB 色匹配函数应满足标准值。"""
    expected = np.array([0.9505, 1.0, 1.0890])
    error = np.abs(WHITE_XYZ - expected).max()
    # r̄(600)≈0.3443（CIE 1931 RGB 标准值核对）
    i600 = int(np.argmin(np.abs(WAVELENGTHS - 600.0)))
    r600_ok = abs(RGB_CMF_1931_2[i600, 0] - 0.3443) < 0.01
    return error < 0.002 and r600_ok
